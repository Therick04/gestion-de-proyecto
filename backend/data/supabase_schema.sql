-- 1. CLIENTES ---------------------------------------------------
create table if not exists public.clientes (
  id               bigint generated always as identity primary key,
  nombres          varchar(100),
  apellidos        varchar(100),
  capital_aportado numeric(18,4)  default 2 check (capital_aportado > 0),
  created_at       timestamptz    default now()
);

-- 2. ROLES ------------------------------------------------------
create table if not exists public.roles (
  id        bigint generated always as identity primary key,
  role_name varchar(50) unique,
  status    smallint    default 1 check (status in (0, 1))
);

-- 3. ESTADO DEL BOT (autoincrementable; el backend usa id = 1) --
create table if not exists public.estado_bot (
  id                      bigint generated by default as identity primary key,
  capital_total_invertido numeric(18,4) default 0,
  balance_actual_bot      numeric(18,4) default 0,
  updated_at              timestamptz   default now()
);

-- 4. HISTORIAL DE OPERACIONES -----------------------------------
create table if not exists public.historial_operaciones (
  id                     bigint generated always as identity primary key,
  fecha                  timestamptz   default now(),
  tipo                   varchar(50)   default 'balance_update',
  balance_anterior       numeric(18,4),
  balance_nuevo          numeric(18,4),
  profit_neto            numeric(18,4),
  rendimiento_porcentaje numeric(10,4),
  nota                   varchar(255)
);

create index if not exists idx_historial_fecha on public.historial_operaciones (fecha desc);

-- 5. SEGURIDAD (Row Level Security) -----------------------------
-- RLS activado SIN políticas públicas: nadie con la clave "anon" puede leer/escribir.
-- El backend usa la clave "service_role", que ignora RLS.
alter table public.clientes              enable row level security;
alter table public.roles                 enable row level security;
alter table public.estado_bot            enable row level security;
alter table public.historial_operaciones enable row level security;

