-- 7. VISTA OPCIONAL: profit proporcional por cliente -------------
create or replace view public.v_profit_clientes
with (security_invoker = true) as
select
  c.id, c.nombres, c.apellidos, c.capital_aportado,
  round(c.capital_aportado / nullif(t.total, 0) * (b.balance_actual_bot - t.total), 4) as profit_ganado
from public.clientes c
cross join (select coalesce(sum(capital_aportado), 0) as total from public.clientes) t
cross join (select balance_actual_bot from public.estado_bot where id = 1) b;
